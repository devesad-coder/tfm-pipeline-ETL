def perform_tactical_feature_engineering(df_limpio: pd.DataFrame) -> pd.DataFrame:
    """Añade características tácticas al DataFrame limpio, como la zona y el carril del campo.
    También crea una bandera para acciones en zona de creación/peligro.
    """
    start_time = time.time()
    logger.info("Iniciando feature engineering táctico.")
    df_tactico = df_limpio.copy() # Crea una copia del DataFrame

    # Función para clasificar la zona del campo según la coordenada X
    def clasificar_zona_x(x):
        if pd.isna(x): return "Sin Ubicación"
        elif x < 40: return "1. Zona Defensiva"
        elif x < 80: return "2. Zona de Creación"
        else: return "3. Zona de Peligro / Último Tercio"

    # Función para clasificar el carril del campo según la coordenada Y
    def clasificar_carril_y(y):
        if pd.isna(y): return "Sin Ubicación"
        elif y < 26.6: return "Banda Izquierda"
        elif y < 53.3: return "Carril Central"
        else: return "Banda Derecha"

    # Aplica las funciones para crear nuevas columnas de zona y carril
    df_tactico['ZONA_CAMPO'] = df_tactico['UBICACION_X'].apply(clasificar_zona_x)
    df_tactico['CARRIL_CAMPO'] = df_tactico['UBICACION_Y'].apply(clasificar_carril_y)
    # Crea una bandera si la acción ocurre en una zona de creación o peligro y es un pase
    df_tactico['ES_ZONA_CREACION_PELIGRO'] = df_tactico.apply(
        lambda row: 1 if (not pd.isna(row['UBICACION_X']) and row['UBICACION_X'] > 102 and row['TIPO_EVENTO'] == 'Pass') else 0,
        axis=1
    )
    logger.info(f"Transformación táctica avanzada completada. Duración: {time.time() - start_time:.2f} segundos")
    return df_tactico

def generate_pass_networks(df_tactico: pd.DataFrame) -> pd.DataFrame:
    """Genera la red de pases a partir del DataFrame táctico.
    Identifica pases exitosos entre jugadores del mismo equipo y calcula el peso de las conexiones.
    """
    start_time = time.time()
    logger.info("Iniciando generación de redes de pases.")
    df = df_tactico.copy() # Crea una copia del DataFrame

    # Ordena los eventos para identificar secuencias de pases
    df = df.sort_values(by=['ID_PARTIDO', 'MINUTO', 'SEGUNDO']).reset_index(drop=True)
    # Desplaza columnas para identificar el siguiente jugador, equipo y partido en la secuencia
    df['SIGUIENTE_NOMBRE_JUGADOR'] = df['NOMBRE_JUGADOR'].shift(-1)
    df['SIGUIENTE_NOMBRE_EQUIPO'] = df['NOMBRE_EQUIPO'].shift(-1)
    df['SIGUIENTE_ID_PARTIDO'] = df['ID_PARTIDO'].shift(-1)

    # Filtra para obtener solo los pases exitosos entre diferentes jugadores del mismo equipo y partido
    df_pases_exitosos = df[
        (df['TIPO_EVENTO'] == 'Pass') & # El evento debe ser un pase
        (df['SIGUIENTE_NOMBRE_JUGADOR'].notnull()) & # Debe haber un siguiente jugador
        (df['ID_PARTIDO'] == df['SIGUIENTE_ID_PARTIDO']) & # El pase debe ser dentro del mismo partido
        (df['NOMBRE_EQUIPO'] == df['SIGUIENTE_NOMBRE_EQUIPO']) & # El pase debe ser entre jugadores del mismo equipo
        (df['NOMBRE_JUGADOR'] != df['SIGUIENTE_NOMBRE_JUGADOR']) # El pasador y el receptor deben ser diferentes
    ].copy()
    logger.info(f"Filtrado de pases exitosos completado. {len(df_pases_exitosos)} pases detectados.")

    # Agrupa por equipo, pasador y receptor para contar el número de pases (peso de la conexión)
    matriz_conexiones = df_pases_exitosos.groupby(
        ['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR', 'SIGUIENTE_NOMBRE_JUGADOR']
    ).size().reset_index(name='PESO_CONEXION')

    # Renombra la columna para mayor claridad
    matriz_conexiones = matriz_conexiones.rename(columns={'SIGUIENTE_NOMBRE_JUGADOR': 'RECEPTOR_JUGADOR'})
    logger.info(f"Matriz de conexiones de pases generada y renombrada. Duración: {time.time() - start_time:.2f} segundos")
    return matriz_conexiones.sort_values(by='PESO_CONEXION', ascending=False) # Ordena por peso de conexión descendente

def detect_outliers(df_kpis: pd.DataFrame) -> pd.DataFrame:
    """Detecta jugadoras de élite (Outliers) iterando por macro-posición y usando métricas P90."""
    start_time = time.time()
    logger.info("Iniciando detección de anomalías segmentada por posición (P90).")

    # Filtro de ruido: Solo jugadoras con más de 90 minutos jugados
    df = df_kpis[df_kpis['MINUTOS_JUGADOS'] >= 90].copy()

    # 1. Agrupar por Macro-Posiciones tácticas
    def mapear_macro_posicion(pos):
        defensas = ['Center Back', 'Left Back', 'Right Back']
        medios = ['Left Defensive Midfield', 'Right Defensive Midfield', 'Center Defensive Midfield',
                  'Left Midfield', 'Right Midfield', 'Center Midfield',
                  'Left Attacking Midfield', 'Right Attacking Midfield', 'Center Attacking Midfield']
        atacantes = ['Left Wing', 'Right Wing', 'Center Forward']

        if pos in defensas: return 'Defensa'
        elif pos in medios: return 'Mediocentro'
        elif pos in atacantes: return 'Delantero'
        else: return 'Portero'

    df['MACRO_POSICION'] = df['POSICION_PRINCIPAL'].apply(mapear_macro_posicion)

    # 2. Calcular métricas por 90 minutos (P90)
    factor90 = 90 / df['MINUTOS_JUGADOS']
    df['RECUPERACIONES_P90'] = (df['INTERCEPCIONES'] + df['ENTRADAS_EXITOSAS']) * factor90
    df['DESPEJES_P90'] = df['DESPEJES'] * factor90
    df['PASES_COMPLETADOS_P90'] = df['PASES_COMPLETADOS'] * factor90
    df['XA_P90'] = df['XA_ACUMULADO'] * factor90
    df['XG_P90'] = df['XG_ACUMULADO'] * factor90
    df['TIROS_P90'] = df['TIROS_INTENTADOS'] * factor90
    df['PASES_PELIGRO_P90'] = df['PASES_ZONA_PELIGRO'] * factor90

    # 3. Iterar modelo de Machine Learning por línea
    resultados = []
    for posicion in ['Defensa', 'Mediocentro', 'Delantero']:
        df_pos = df[df['MACRO_POSICION'] == posicion].copy()

        if len(df_pos) < 10: # Evitar errores si hay pocos datos
            continue

        # Seleccionar features específicas según el rol
        if posicion == 'Defensa':
            features = ['RECUPERACIONES_P90', 'DESPEJES_P90', 'EFICIENCIA_PASES_%']
        elif posicion == 'Mediocentro':
            features = ['PASES_COMPLETADOS_P90', 'XA_P90', 'EFICIENCIA_PASES_%']
        else: # Delantero
            features = ['XG_P90', 'TIROS_P90', 'PASES_PELIGRO_P90']

        # Entrenar el modelo solo con su grupo
        X = df_pos[features].fillna(0)
        modelo = IsolationForest(contamination=0.06, random_state=42) # 6% de élite por posición
        df_pos['ANOMALIA_SCORE'] = modelo.fit_predict(X)

        df_pos['ESTADO_JUGADOR'] = df_pos.apply(
            lambda row: f"Élite ({posicion})" if row['ANOMALIA_SCORE'] == -1 else 'Estándar',
            axis=1
        )
        resultados.append(df_pos)
        logger.info(f"Modelo Isolation Forest entrenado para {posicion}.")

    df_final_outliers = pd.concat(resultados) if resultados else pd.DataFrame()
    logger.info(f"Detección de anomalías finalizada. Duración: {time.time() - start_time:.2f} segundos")

    return df_final_outliers

def extract_advanced_features_pro(df_pandas: pd.DataFrame) -> pd.DataFrame:
    """Extrae características avanzadas, incluyendo cálculo de xA (Expected Assists) mapeando key_pass_id de los tiros.
    Procesa cada evento para construir un DataFrame con métricas detalladas.
    """
    start_time = time.time()
    logger.info("Iniciando extracción y procesamiento avanzado de datos de eventos (df_pro).")

    # 1. Precomputar un mapa de xG por cada ID de pase clave (key_pass_id) a partir de los tiros
    # Esto se hace para poder asignar el xG de un tiro a la asistencia clave que lo generó (xA)
    key_pass_xg_map = {}
    for _, row in df_pandas.iterrows():
        type_data = row.get('type')
        tipo = type_data.get('name') if isinstance(type_data, dict) else None
        if tipo == 'Shot': # Si el evento es un tiro
            shot_info = row.get('shot', {}) # Obtiene la información del tiro
            if isinstance(shot_info, dict):
                key_pass_id = shot_info.get('key_pass_id') # Obtiene el ID del pase clave
                if key_pass_id:
                    xg_val = float(shot_info.get('statsbomb_xg', 0.0) or 0.0) # Obtiene el xG del tiro
                    # Si múltiples tiros apuntaran al mismo key_pass_id, acumulamos o asignamos
                    key_pass_xg_map[key_pass_id] = key_pass_xg_map.get(key_pass_id, 0.0) + xg_val

    datos_avanzados = [] # Lista para almacenar los registros procesados
    # Itera sobre cada fila del DataFrame de eventos para extraer características
    for idx, row in df_pandas.iterrows():
        # Extrae el tipo de evento, equipo, jugador, ID del partido, ID del evento y ubicación
        type_data = row.get('type')
        tipo = type_data.get('name') if isinstance(type_data, dict) else None

        team_data = row.get('team')
        team = team_data.get('name') if isinstance(team_data, dict) else None

        player_data = row.get('player')
        player = player_data.get('name') if isinstance(player_data, dict) else None

        match_id = row.get('match_id')
        event_id = row.get('id')
        loc = row.get('location')

        # Inicializa un diccionario con las métricas para el evento actual
        reg = {
            'ID_PARTIDO': match_id,
            'NOMBRE_EQUIPO': team,
            'NOMBRE_JUGADOR': player,
            'TIPO_EVENTO': tipo,
            'UBICACION_X': loc[0] if isinstance(loc, list) and len(loc) > 0 else None,
            'UBICACION_Y': loc[1] if isinstance(loc, list) and len(loc) > 1 else None,
            'RESULTADO_PASE': None,
            'ASISTENCIA_GOL_PASE': 0,
            'ASISTENCIA_TIRO_PASE': 0,
            'PASE_XA': 0.0,  # Nuevo campo xA (Expected Assists)
            'TIRO_XG': 0.0,
            'RESULTADO_TIRO': None,
            'CONDUCCION_FIN_X': None,
            'CONDUCCION_FIN_Y': None,
            'CONDUCCION_DISTANCIA': 0.0,
            'PASE_INTENTADO': 0,
            'PASE_EXITOSO': 0,
            'TIROS_INTENTADOS': 0,  # Nuevo campo para tiros totales intentados
            'GOL_MARCADO': 0,
            'RESULTADO_REGATE': None,
            'PRESIONES_INTENTADAS': 0,
            'PRESIONES_ULTIMO_TERCIO': 0,
            'ENTRADAS_INTENTADAS': 0,
            'ENTRADAS_EXITOSAS': 0,
            'INTERCEPCIONES': 0,
            'BLOQUEOS': 0,
            'DESPEJES': 0,
            # Nuevos campos para pases en zonas y dirección
            'PASES_ZONA_PELIGRO': 0,
            'PASES_ZONA_NO_PELIGRO': 0,
            'PASES_ZONA_PELIGRO_ADELANTE': 0,
            'PASES_ZONA_PELIGRO_ATRAS': 0,
            'PASES_ZONA_NO_PELIGRO_ADELANTE': 0,
            'PASES_ZONA_NO_PELIGRO_ATRAS': 0
        }

        # Lógica de procesamiento para eventos de tipo 'Pass'
        if tipo == 'Pass':
            reg['PASE_INTENTADO'] = 1 # Marca el pase como intentado
            pass_info = row.get('pass', {}) # Obtiene la información del pase
            if isinstance(pass_info, dict):
                outcome_pass = pass_info.get('outcome') # Resultado del pase
                end_loc = pass_info.get('end_location') # Ubicación final del pase

                if outcome_pass is None: # Si no hay un resultado explícito, se considera completo
                    reg['RESULTADO_PASE'] = 'Complete'
                    reg['PASE_EXITOSO'] = 1
                else:
                    out_name = outcome_pass.get('name') if isinstance(outcome_pass, dict) else str(outcome_pass)
                    reg['RESULTADO_PASE'] = out_name
                    # Si el resultado indica un pase fallido, marca PASE_EXITOSO como 0
                    if out_name in ['Incomplete', 'Out', 'Pass Offside', 'Injury', 'Unknown', 'Blocked', 'Incomplete Dangerous']:
                        reg['PASE_EXITOSO'] = 0
                    else:
                        reg['PASE_EXITOSO'] = 1

                # Clasificar pases por zona y dirección (adelante/atrás)
                if reg['UBICACION_X'] is not None and end_loc is not None and len(end_loc) > 0:
                    pass_start_x = reg['UBICACION_X'] # Coordenada X de inicio del pase
                    pass_end_x = end_loc[0] # Coordenada X de fin del pase

                    is_danger_zone = pass_start_x >= 80 # Verifica si el pase se origina en zona de peligro
                    # Define si es un pase hacia adelante o hacia atrás con un pequeño umbral
                    is_forward_pass = pass_end_x > pass_start_x + 1
                    is_backward_pass = pass_end_x < pass_start_x - 1

                    if is_danger_zone: # Si es en zona de peligro
                        reg['PASES_ZONA_PELIGRO'] = 1
                        if is_forward_pass:
                            reg['PASES_ZONA_PELIGRO_ADELANTE'] = 1
                        elif is_backward_pass:
                            reg['PASES_ZONA_PELIGRO_ATRAS'] = 1
                    else: # Si no es en zona de peligro
                        reg['PASES_ZONA_NO_PELIGRO'] = 1
                        if is_forward_pass:
                            reg['PASES_ZONA_NO_PELIGRO_ADELANTE'] = 1
                        elif is_backward_pass:
                            reg['PASES_ZONA_NO_PELIGRO_ATRAS'] = 1

                # Marca si el pase fue asistencia de gol o asistencia de tiro
                if pass_info.get('goal_assist') is True:
                    reg['ASISTENCIA_GOL_PASE'] = 1
                if pass_info.get('shot_assist') is True:
                    reg['ASISTENCIA_TIRO_PASE'] = 1
                    # Asigna xA utilizando el key_pass_id o el mapa precomputado si coincide con el event_id
                    if event_id in key_pass_xg_map:
                        reg['PASE_XA'] = key_pass_xg_map[event_id]
            else: # Si no hay información de pase detallada, asume pase completo
                reg['RESULTADO_PASE'] = 'Complete'
                reg['PASE_EXITOSO'] = 1
                # Para pases completos implícitos, no hay ubicación final, así que no se puede determinar la dirección
                if reg['UBICACION_X'] is not None:
                    if reg['UBICACION_X'] >= 80:
                        reg['PASES_ZONA_PELIGRO'] = 1
                    else:
                        reg['PASES_ZONA_NO_PELIGRO'] = 1

        # Lógica de procesamiento para eventos de tipo 'Shot'
        elif tipo == 'Shot':
            reg['TIROS_INTENTADOS'] = 1  # Conteo de tiros intentados
            shot_info = row.get('shot', {}) # Obtiene la información del tiro
            if isinstance(shot_info, dict):
                reg['TIRO_XG'] = float(shot_info.get('statsbomb_xg', 0.0) or 0.0) # Obtiene el xG del tiro
                outcome_shot = shot_info.get('outcome') # Resultado del tiro
                if isinstance(outcome_shot, dict):
                    reg['RESULTADO_TIRO'] = outcome_shot.get('name')
                elif isinstance(outcome_shot, str):
                    reg['RESULTADO_TIRO'] = outcome_shot

                if reg['RESULTADO_TIRO'] == 'Goal': # Si el resultado es gol
                    reg['GOL_MARCADO'] = 1 # Marca como gol

        # Lógica de procesamiento para eventos de tipo 'Dribble'
        elif tipo == 'Dribble':
            dribble_info = row.get('dribble', {}) # Obtiene la información del regate
            if isinstance(dribble_info, dict):
                outcome_dribble = dribble_info.get('outcome') # Resultado del regate
                if isinstance(outcome_dribble, dict):
                    reg['RESULTADO_REGATE'] = outcome_dribble.get('name')
                elif isinstance(outcome_dribble, str):
                    reg['RESULTADO_REGATE'] = outcome_dribble

        # Lógica de procesamiento para eventos de tipo 'Carry' (conducción)
        elif tipo == 'Carry':
            carry_info = row.get('carry', {}) # Obtiene la información de la conducción
            if isinstance(carry_info, dict):
                end_loc = carry_info.get('end_location') # Ubicación final de la conducción
                if isinstance(end_loc, list) and len(end_loc) >= 2:
                    reg['CONDUCCION_FIN_X'] = end_loc[0]
                    reg['CONDUCCION_FIN_Y'] = end_loc[1]
                    if reg['UBICACION_X'] is not None and reg['UBICACION_Y'] is not None:
                        # Calcula la distancia euclidiana de la conducción
                        dist = np.sqrt((end_loc[0] - reg['UBICACION_X'])**2 + (end_loc[1] - reg['UBICACION_Y'])**2)
                        reg['CONDUCCION_DISTANCIA'] = round(dist, 2)

        # Lógica de procesamiento para eventos de tipo 'Pressure'
        elif tipo == 'Pressure':
            reg['PRESIONES_INTENTADAS'] = 1 # Marca la presión como intentada
            # Si la presión ocurre en el último tercio del campo
            if reg['UBICACION_X'] is not None and reg['UBICACION_X'] > 80:
                reg['PRESIONES_ULTIMO_TERCIO'] = 1

        # Lógica de procesamiento para eventos de tipo 'Duel' (duelo)
        elif tipo == 'Duel':
            duel_info = row.get('duel', {}) # Obtiene la información del duelo
            if isinstance(duel_info, dict):
                duel_type = duel_info.get('type', {}).get('name') # Tipo de duelo
                duel_outcome = duel_info.get('outcome', {}).get('name') # Resultado del duelo
                if duel_type == 'Tackle': # Si el duelo es una entrada
                    reg['ENTRADAS_INTENTADAS'] = 1 # Marca la entrada como intentada
                    if duel_outcome in ['Won', 'Success in Play']: # Si la entrada fue exitosa
                        reg['ENTRADAS_EXITOSAS'] = 1

        # Lógica de procesamiento para eventos de tipo 'Interception'
        elif tipo == 'Interception':
            interception_info = row.get('interception', {}) # Obtiene la información de la intercepción
            if isinstance(interception_info, dict):
                interception_outcome = interception_info.get('outcome', {}).get('name') # Resultado de la intercepción
                if interception_outcome == 'Won': # Si la intercepción fue exitosa
                     reg['INTERCEPCIONES'] = 1

        # Lógica de procesamiento para eventos de tipo 'Block' (bloqueo)
        elif tipo == 'Block':
            reg['BLOQUEOS'] = 1 # Marca el bloqueo

        # Lógica de procesamiento para eventos de tipo 'Clearance' (despeje)
        elif tipo == 'Clearance':
            reg['DESPEJES'] = 1 # Marca el despeje

        datos_avanzados.append(reg) # Añade el registro de métricas a la lista

    df_pro = pd.DataFrame(datos_avanzados) # Crea el DataFrame final con características avanzadas
    logger.info(f"DataFrame df_pro creado con éxito a partir de datos avanzados de eventos. Duración: {time.time() - start_time:.2f} segundos")
    return df_pro

def calculate_final_kpis_from_pro(df_pro: pd.DataFrame) -> pd.DataFrame:
    """Calcula los KPIs finales incorporando TIROS_INTENTADOS, TASA_CONVERSION_TIRO, GOLES_MENOS_XG y XA_ACUMULADO.
    Agrupa por equipo y jugador para obtener métricas agregadas y ratios de eficiencia.
    """
    start_time = time.time()
    logger.info("Iniciando cálculo de KPIs finales (df_kpis_finales).")
    # Agrupa por equipo y jugador y agrega las métricas relevantes
    df_kpis_finales = df_pro.groupby(['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR']).agg(
        TOTAL_ACCIONES=('TIPO_EVENTO', 'count'),
        METROS_CONDUCIDOS_TOTALES=('CONDUCCION_DISTANCIA', 'sum'),
        PASES_INTENTADOS=('PASE_INTENTADO', 'sum'),
        PASES_COMPLETADOS=('PASE_EXITOSO', 'sum'),
        # Agregados para pases en zonas
        PASES_ZONA_PELIGRO=('PASES_ZONA_PELIGRO', 'sum'),
        PASES_ZONA_NO_PELIGRO=('PASES_ZONA_NO_PELIGRO', 'sum'),
        # Nuevos agregados para pases en zonas y dirección
        PASES_ZONA_PELIGRO_ADELANTE=('PASES_ZONA_PELIGRO_ADELANTE', 'sum'),
        PASES_ZONA_PELIGRO_ATRAS=('PASES_ZONA_PELIGRO_ATRAS', 'sum'),
        PASES_ZONA_NO_PELIGRO_ADELANTE=('PASES_ZONA_NO_PELIGRO_ADELANTE', 'sum'),
        PASES_ZONA_NO_PELIGRO_ATRAS=('PASES_ZONA_NO_PELIGRO_ATRAS', 'sum'),
        TIROS_INTENTADOS=('TIROS_INTENTADOS', 'sum'),
        GOLES_REALES=('GOL_MARCADO', 'sum'),
        XG_ACUMULADO=('TIRO_XG', 'sum'),
        XA_ACUMULADO=('PASE_XA', 'sum'),
        ASISTENCIAS_GOL=('ASISTENCIA_GOL_PASE', 'sum'),
        ASISTENCIAS_TIRO=('ASISTENCIA_TIRO_PASE', 'sum'),
        REGATES_INTENTADOS=('RESULTADO_REGATE', lambda x: (x.notnull()).sum()), # Cuenta regates intentados
        REGATES_EXITOSOS=('RESULTADO_REGATE', lambda x: (x == 'Complete').sum()), # Cuenta regates exitosos
        PRESIONES_INTENTADAS=('PRESIONES_INTENTADAS', 'sum'),
        PRESIONES_ULTIMO_TERCIO=('PRESIONES_ULTIMO_TERCIO', 'sum'),
        ENTRADAS_INTENTADAS=('ENTRADAS_INTENTADAS', 'sum'),
        ENTRADAS_EXITOSAS=('ENTRADAS_EXITOSAS', 'sum'),
        INTERCEPCIONES=('INTERCEPCIONES', 'sum'),
        BLOQUEOS=('BLOQUEOS', 'sum'),
        DESPEJES=('DESPEJES', 'sum')
    ).reset_index()

    # Cálculos de ratios y eficiencias
    df_kpis_finales['EFICIENCIA_PASES_%'] = np.where(
        df_kpis_finales['PASES_INTENTADOS'] > 0,
        round((df_kpis_finales['PASES_COMPLETADOS'] / df_kpis_finales['PASES_INTENTADOS']) * 100, 2),
        0.0
    )
    df_kpis_finales['EFICIENCIA_REGATES_%'] = np.where(
        df_kpis_finales['REGATES_INTENTADOS'] > 0,
        round((df_kpis_finales['REGATES_EXITOSOS'] / df_kpis_finales['REGATES_INTENTADOS']) * 100, 2),
        0.0
    )
    df_kpis_finales['EFICIENCIA_ENTRADAS_%'] = np.where(
        df_kpis_finales['ENTRADAS_INTENTADAS'] > 0,
        round((df_kpis_finales['ENTRADAS_EXITOSAS'] / df_kpis_finales['ENTRADAS_INTENTADAS']) * 100, 2),
        0.0
    )

    # 1. Tasa de conversión de tiro (Goles / Tiros)
    df_kpis_finales['TASA_CONVERSION_TIRO_%'] = np.where(
        df_kpis_finales['TIROS_INTENTADOS'] > 0,
        round((df_kpis_finales['GOLES_REALES'] / df_kpis_finales['TIROS_INTENTADOS']) * 100, 2),
        0.0
    )

    # 2. Diferencial de finalización o Goles Menos xG (Goles - xG)
    df_kpis_finales['GOLES_MENOS_XG'] = round(df_kpis_finales['GOLES_REALES'] - df_kpis_finales['XG_ACUMULADO'], 2)

    df_kpis_finales = df_kpis_finales.sort_values(by='XG_ACUMULADO', ascending=False) # Ordena por xG acumulado
    logger.info(f"KPIs finales calculados con éxito. Duración: {time.time() - start_time:.2f} segundos")
    return df_kpis_finales

def integrate_player_positions_to_kpis(df_kpis_finales: pd.DataFrame, df_pandas: pd.DataFrame, df_pro: pd.DataFrame) -> pd.DataFrame:
    """Integra las posiciones de los jugadores, partidos de titular y minutos jugados a los KPIs finales,
       e infiere posiciones para 'Rotación / Suplente' basándose en la ubicación media de sus eventos.
    """
    start_time = time.time()
    logger.info("Integrando posiciones de jugadores, partidos de titular y minutos jugados a los KPIs finales.")

    df_kpis_finales_copy = df_kpis_finales.copy() # Crea una copia del DataFrame de KPIs

    # --- 1. Extraer posiciones y partidos de titular (Starting XI) ---
    # Filtra eventos de tipo 'Starting XI' para obtener las alineaciones iniciales
    starting_xi_events = df_pandas[df_pandas['type'].apply(lambda x: x.get('name') if isinstance(x, dict) else None) == 'Starting XI']
    posiciones_data = []
    for idx, row in starting_xi_events.iterrows():
        match_id = row['match_id']
        team_name = row['team'].get('name') if isinstance(row.get('team'), dict) else None
        player_name = row['player'].get('name') if isinstance(row.get('player'), dict) else None # Obtiene el nombre del jugador del evento 'Starting XI'
        tactics = row.get('tactics', {}) # Obtiene la información táctica
        if isinstance(tactics, dict) and 'lineup' in tactics:
            for player_entry in tactics['lineup']:
                player_name_lineup = player_entry.get('player', {}).get('name')
                position_name = player_entry.get('position', {}).get('name')
                if team_name and player_name_lineup and position_name:
                    posiciones_data.append({
                        'ID_PARTIDO': match_id,
                        'NOMBRE_EQUIPO': team_name,
                        'NOMBRE_JUGADOR': player_name_lineup,
                        'POSICION_PRINCIPAL': position_name
                    })
    df_pos_mapping = pd.DataFrame(posiciones_data) # Crea un DataFrame con las posiciones mapeadas

    # Calcula el número de partidos de titular para cada jugador
    df_partidos_titular = df_pos_mapping.groupby(['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR'])['ID_PARTIDO'].nunique().reset_index(name='PARTIDOS_TITULAR')
    # Conserva solo la primera posición distinta para cada jugador para 'POSICION_PRINCIPAL'
    df_pos_principal = df_pos_mapping.drop_duplicates(subset=['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR', 'POSICION_PRINCIPAL']).groupby(['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR']).first().reset_index()
    df_pos_principal = df_pos_principal[['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR', 'POSICION_PRINCIPAL']]

    # --- 2. Calcular minutos jugados ---
    df_players_events = df_pandas.copy() # Crea una copia del DataFrame de eventos
    df_players_events['NOMBRE_EQUIPO'] = df_players_events['team'].apply(lambda x: x.get('name') if isinstance(x, dict) else None)
    df_players_events['NOMBRE_JUGADOR'] = df_players_events['player'].apply(lambda x: x.get('name') if isinstance(x, dict) else None)

    # Calcula el minuto máximo jugado por cada jugador en cada partido
    df_minutes = df_players_events.groupby(['match_id', 'NOMBRE_EQUIPO', 'NOMBRE_JUGADOR'])['minute'].max().reset_index()
    df_minutes = df_minutes.rename(columns={'minute': 'MINUTOS_MAX_PARTIDO', 'match_id': 'ID_PARTIDO'})

    # Suma los minutos jugados en todos los partidos para cada jugador
    df_total_minutes = df_minutes.groupby(['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR'])['MINUTOS_MAX_PARTIDO'].sum().reset_index(name='MINUTOS_JUGADOS')

    # --- 3. Unir toda la información a df_kpis_finales ---
    # Elimina la columna 'POSICION_PRINCIPAL' si ya existe para evitar errores en la fusión
    if 'POSICION_PRINCIPAL' in df_kpis_finales_copy.columns:
        df_kpis_finales_copy = df_kpis_finales_copy.drop(columns=['POSICION_PRINCIPAL'])

    # Fusiona el DataFrame de KPIs con las posiciones principales
    df_kpis_finales_copy = pd.merge(
        df_kpis_finales_copy,
        df_pos_principal,
        on=['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR'],
        how='left'
    )
    # Fusiona con los partidos de titular
    df_kpis_finales_copy = pd.merge(
        df_kpis_finales_copy,
        df_partidos_titular,
        on=['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR'],
        how='left'
    )
    # Fusiona con los minutos jugados
    df_kpis_finales_copy = pd.merge(
        df_kpis_finales_copy,
        df_total_minutes,
        on=['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR'],
        how='left'
    )

    # --- 4. Inferir posiciones para 'Rotación / Suplente' ---
    # Rellena los valores nulos iniciales de 'POSICION_PRINCIPAL' con 'Rotación / Suplente'
    df_kpis_finales_copy['POSICION_PRINCIPAL'] = df_kpis_finales_copy['POSICION_PRINCIPAL'].fillna('Rotación / Suplente')

    # Obtiene los jugadores que necesitan inferencia de posición
    players_to_infer = df_kpis_finales_copy[df_kpis_finales_copy['POSICION_PRINCIPAL'] == 'Rotación / Suplente']

    if not players_to_infer.empty:
        logger.info(f"Iniciando inferencia de posición para {len(players_to_infer)} jugadores con posición 'Rotación / Suplente'.")

        # Calcula la ubicación promedio (x, y) para cada jugador a partir de df_pro
        avg_locations = df_pro.groupby(['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR']).agg(
            AVG_UBICACION_X=('UBICACION_X', 'mean'),
            AVG_UBICACION_Y=('UBICACION_Y', 'mean')
        ).reset_index()

        # Unir las ubicaciones promedio con los KPIs finales para los jugadores a inferir
        df_kpis_finales_copy = pd.merge(
            df_kpis_finales_copy,
            avg_locations,
            on=['NOMBRE_EQUIPO', 'NOMBRE_JUGADOR'],
            how='left'
        )

        # Aplica la función de inferencia de posición solo a los jugadores con 'Rotación / Suplente'
        for index, row in df_kpis_finales_copy.iterrows():
            if row['POSICION_PRINCIPAL'] == 'Rotación / Suplente':
                inferred_pos = infer_position_from_coordinates(row['AVG_UBICACION_X'], row['AVG_UBICACION_Y'])
                if inferred_pos:
                    df_kpis_finales_copy.loc[index, 'POSICION_PRINCIPAL'] = inferred_pos
                    logger.debug(f"Posición inferida para {row['NOMBRE_JUGADOR']} ({row['NOMBRE_EQUIPO']}): {inferred_pos}")

        # Elimina las columnas temporales de ubicación promedio una vez que la inferencia ha terminado
        df_kpis_finales_copy = df_kpis_finales_copy.drop(columns=['AVG_UBICACION_X', 'AVG_UBICACION_Y'], errors='ignore')
        logger.info("Inferencia de posiciones completada.")

    # Rellena los valores nulos de 'PARTIDOS_TITULAR' y 'MINUTOS_JUGADOS' con 0 y convierte a entero
    df_kpis_finales_copy['PARTIDOS_TITULAR'] = df_kpis_finales_copy['PARTIDOS_TITULAR'].fillna(0).astype(int)
    df_kpis_finales_copy['MINUTOS_JUGADOS'] = df_kpis_finales_copy['MINUTOS_JUGADOS'].fillna(0).astype(int)

    logger.info(f"Posiciones, partidos de titular y minutos jugados integrados con éxito. Duración: {time.time() - start_time:.2f} segundos")
    return df_kpis_finales_copy

