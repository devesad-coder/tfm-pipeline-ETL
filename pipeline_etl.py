def ingest_events(db, partidos: list, folder_path: str):
    """Ingesta datos de eventos en MongoDB para cada partido, buscando el archivo JSON correspondiente."""
    start_time = time.time()
    coleccion_eventos = db['eventos'] # Accede a la colección 'eventos'
    logger.info("Iniciando ingesta masiva de eventos de la temporada.")
    try:
        coleccion_eventos.delete_many({}) # Elimina documentos existentes en la colección
        logger.info("Datos previos de eventos eliminados (si existían).")

        eventos_totales_insertados = 0
        # Itera sobre cada partido para encontrar sus eventos correspondientes
        for partido in partidos:
            match_id = str(partido['match_id']) # Obtiene el ID del partido
            archivo_json = os.path.join(folder_path, f"{match_id}.json") # Construye la ruta al archivo de eventos

            if os.path.exists(archivo_json):
                try:
                    with open(archivo_json, encoding='utf-8') as file:
                        eventos = json.load(file)
                    for evento in eventos:
                        evento['match_id'] = match_id # Añade el ID del partido a cada evento
                    coleccion_eventos.insert_many(eventos) # Inserta los eventos del partido
                    eventos_totales_insertados += len(eventos)
                    logger.info(f"Partido {match_id} ingerido. ({len(eventos)} eventos)")
                except Exception as e:
                    logger.error(f"Error al procesar o insertar eventos para el partido {match_id}: {e}")
            else:
                logger.warning(f"Archivo {archivo_json} no encontrado en {folder_path}. Saltando este partido.")
        logger.info(f"RESUMEN: Total de {eventos_totales_insertados} eventos inyectados en MongoDB Atlas. Duración: {time.time() - start_time:.2f} segundos")
    except Exception as e:
        logger.error(f"Error durante la ingesta masiva de eventos: {e}")
        raise

