def upload_data_to_snowflake(dfs_to_upload: dict):
    """Carga DataFrames a Snowflake.
    Establece conexión, elimina tablas existentes y sube los DataFrames especificados.
    """
    start_time = time.time()
    logger.info("Iniciando proceso de carga a Snowflake.")
    try:
        # Establece la conexión con Snowflake utilizando las credenciales de las variables de entorno
        ctx = snowflake.connector.connect(
            user=SNOWFLAKE_USER,
            password=SNOWFLAKE_PASSWORD,
            account=SNOWFLAKE_ACCOUNT,
            warehouse=SNOWFLAKE_WAREHOUSE,
            database=SNOWFLAKE_DATABASE,
            schema=SNOWFLAKE_SCHEMA
        )
        logger.info("Conexión establecida con éxito en Snowflake!")
    except Exception as e:
        logger.critical(f"Error CRÍTICO al conectar con Snowflake: {e}")
        raise

    # Itera sobre cada DataFrame a subir
    for nombre_tabla, df in dfs_to_upload.items():
        if df.empty:
            logger.warning(f"Saltando la carga de la tabla '{nombre_tabla}' porque el DataFrame está vacío.")
            continue

        df_temp = df.copy() # Crea una copia temporal del DataFrame
        df_temp.columns = [str(col).upper() for col in df_temp.columns] # Convierte los nombres de las columnas a mayúsculas para Snowflake
        df_temp = df_temp.reset_index(drop=True) # Resetea el índice del DataFrame
        logger.info(f"Preparando la tabla '{nombre_tabla}' para la carga.")

        cursor = ctx.cursor() # Crea un cursor para ejecutar comandos SQL
        try:
            cursor.execute(f"DROP TABLE IF EXISTS {nombre_tabla}") # Elimina la tabla si ya existe
            logger.info(f"Tabla '{nombre_tabla}' borrada previamente en Snowflake (si existía).")
            # Escribe el DataFrame en Snowflake, creando la tabla automáticamente si no existe
            success, nchunks, nrows, _ = write_pandas(ctx, df_temp, nombre_tabla, auto_create_table=True)
            logger.info(f"Tabla {nombre_tabla} cargada con éxito: {nrows} filas subidas.")
        except Exception as e:
            logger.error(f"Error al subir {nombre_tabla} a Snowflake: {e}")
        finally:
            cursor.close() # Cierra el cursor
    ctx.close() # Cierra la conexión a Snowflake
    logger.info("Conexión a Snowflake cerrada.")
    logger.info(f"Proceso de carga a Snowflake completado. Duración: {time.time() - start_time:.2f} segundos")

# ============================================================================
#                          FUNCIÓN PRINCIPAL DEL PIPELINE
# ============================================================================
def run_etl_pipeline():
    """Orquesta la ejecución de todo el pipeline ETL.
    Define la secuencia de pasos: ingesta, procesamiento, cálculo de KPIs y carga a Snowflake.
    """
    pipeline_start_time = time.time()
    logger.info("===========================================================")
    logger.info("           INICIANDO EJECUCIÓN DEL PIPELINE ETL         ")
    logger.info("===========================================================")

    mongo_client = None # Inicializa el cliente de MongoDB a None
    try:
        # Conexión a MongoDB Atlas
        mongo_client, db = get_mongo_client(URI_ATLAS)

        # Ingesta de datos en MongoDB (competiciones, partidos, eventos)
        ingest_competitions(db, COMPETITIONS_FOLDER)
        partidos_data = ingest_matches(db, MATCHES_FOLDER)
        ingest_events(db, partidos_data, EVENTS_FOLDER)

        # Carga de datos de eventos desde MongoDB a Pandas y limpieza inicial
        df_pandas = load_events_from_mongo_to_pandas(db)
        df_limpio = clean_and_normalize_data(df_pandas)

        # Feature Engineering táctico y cálculos de KPIs
        df_tactico = perform_tactical_feature_engineering(df_limpio)
        df_red_final = generate_pass_networks(df_tactico)


        # Path alternativo para df_kpis_finales: extracción de características avanzadas y cálculo de KPIs finales
        df_pro = extract_advanced_features_pro(df_pandas)
        df_kpis_finales = calculate_final_kpis_from_pro(df_pro)
        # Integración de posiciones de jugadores y minutos jugados
        df_kpis_finales = integrate_player_positions_to_kpis(df_kpis_finales, df_pandas, df_pro)

        #Ejecutar el Machine Learning con los kpis integrados
        df_outliers_afin = detect_outliers(df_kpis_finales)

        # Preparar DataFrames para subir a Snowflake (KPIs, red de pases, anomalías)
        dfs_to_upload = {
            'GOLD_KPIS_JUGADORES': df_kpis_finales,
            'GOLD_RED_PASES': df_red_final,
            'GOLD_JUGADORES_ANOMALIAS': df_outliers_afin
        }

        # Cargar los DataFrames procesados a Snowflake
        upload_data_to_snowflake(dfs_to_upload)

        logger.info("===========================================================")
        logger.info(f"           PIPELINE ETL EJECUTADO CON ÉXITO. Duración total: {time.time() - pipeline_start_time:.2f} segundos")
        logger.info("===========================================================")

    except Exception as e:
        # Captura y registra cualquier error crítico que ocurra en el pipeline
        logger.critical(f"El pipeline ETL ha fallado con un error CRÍTICO: {e}", exc_info=True)
        logger.info("===========================================================")
        logger.info(f"           PIPELINE ETL FINALIZADO CON ERRORES. Duración total: {time.time() - pipeline_start_time:.2f} segundos")
        logger.info("===========================================================")
    finally:
        # Asegura que la conexión a MongoDB se cierre al finalizar el pipeline
        if mongo_client:
            mongo_client.close()
            logger.info("Conexión a MongoDB cerrada.")
        logging.shutdown() # Cierra el sistema de logging

# Punto de entrada principal para la ejecución del script
if __name__ == '__main__':
    run_etl_pipeline()
